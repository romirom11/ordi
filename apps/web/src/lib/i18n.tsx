const DICTS: Record<Locale, Dict> = { en, uk };

/**
 * Feature modules register their own strings at import time via extendDict –
 * this keeps page-specific keys next to the page instead of in this file, and
 * lets independent features add strings without touching a shared file.
 * Must be called at module top level (before components render).
 */
export function extendDict(dicts: { en: Dict; uk: Dict }): void {
  Object.assign(DICTS.en, dicts.en);
  Object.assign(DICTS.uk, dicts.uk);
}

interface I18n {
  locale: Locale;
  t: (key: string, fallback?: string) => string;
}

const I18nContext = createContext<I18n>({ locale: 'en', t: (k, f) => f ?? k });

export function I18nProvider({ locale, children }: { locale: string; children: ReactNode }) {
  const loc: Locale = locale === 'uk' ? 'uk' : 'en';
  const value = useMemo<I18n>(() => ({
    locale: loc,
    t: (key, fallback) => DICTS[loc][key] ?? DICTS.en[key] ?? fallback ?? key,
  }), [loc]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useT(): (key: string, fallback?: string) => string {
  return useContext(I18nContext).t;
}

export function useLocale(): Locale {
  return useContext(I18nContext).locale;
}

/** Pre-login locale (login page): browser or last-used. */
export function guessLocale(): Locale {
  try {
    const stored = localStorage.getItem('ordi:locale');
    if (stored === 'uk' || stored === 'en') return stored;
  } catch { /* ignore */ }
  return navigator.language?.startsWith('uk') ? 'uk' : 'en';
}

export function rememberLocale(locale: string): void {
  try { localStorage.setItem('ordi:locale', locale); } catch { /* ignore */ }
}
